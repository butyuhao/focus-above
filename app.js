const passportCovers = {
  'zh-Hans': 'assets/passport-zh-hans.png',
  'zh-Hant': 'assets/passport-zh-hant.png',
  en: 'assets/passport-en.png'
};

const picker = document.querySelector('#language');

function applyLanguage(language) {
  const selected = copy[language] || copy['zh-Hans'];
  document.documentElement.lang = language;
  document.querySelectorAll('[data-copy]').forEach((element) => {
    const value = selected[element.dataset.copy];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll('[data-alt]').forEach((element) => {
    const value = selected[element.dataset.alt];
    if (value) element.alt = value;
  });
  document.querySelector('#passport-cover').src = passportCovers[language] || passportCovers['zh-Hans'];
  localStorage.setItem('focusAboveMarketingLanguage', language);
}

const savedLanguage = localStorage.getItem('focusAboveMarketingLanguage');
const browserLanguage = navigator.language.toLowerCase();
const initialLanguage = savedLanguage || (browserLanguage.includes('zh-hant') || browserLanguage.includes('zh-hk') || browserLanguage.includes('zh-tw') ? 'zh-Hant' : browserLanguage.startsWith('zh') ? 'zh-Hans' : 'en');
picker.value = initialLanguage;
applyLanguage(initialLanguage);
picker.addEventListener('change', (event) => applyLanguage(event.target.value));
